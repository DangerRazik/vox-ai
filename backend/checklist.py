def checklist_for_prompt(enabled_ids=None) -> str:
    """Сериализация чек-листа в текст для LLM."""
    lines = []
    for c in CHECKLIST:
        if enabled_ids is not None and c['id'] not in enabled_ids:
            continue
        lines.append(f'[{c["id"]}] {c["block"]} / {c["title"]} (max {c["max"]})')
        lines.append(f'    Критерии: {c["criteria"]}')
    return "\n".join(lines)
